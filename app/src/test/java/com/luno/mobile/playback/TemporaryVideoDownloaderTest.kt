package com.luno.mobile.playback

import com.google.common.truth.Truth.assertThat
import java.util.concurrent.TimeUnit
import kotlinx.coroutines.async
import kotlinx.coroutines.cancelAndJoin
import kotlinx.coroutines.runBlocking
import okhttp3.OkHttpClient
import okhttp3.mockwebserver.MockResponse
import okhttp3.mockwebserver.MockWebServer
import okhttp3.mockwebserver.SocketPolicy
import okio.Buffer
import okio.buffer
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder

class TemporaryVideoDownloaderTest {
    @get:Rule val temporary = TemporaryFolder()
    private fun fixture(): ByteArray = javaClass.getResourceAsStream("/video/temporary-video.mp4")!!.use { it.readBytes() }

    @Test fun actualH264Mp4PublishesAtomicallyOnlyAfterAllBytesArrive(): Unit = runBlocking {
        MockWebServer().use { server ->
            val bytes = fixture()
            server.enqueue(MockResponse().setHeader("Content-Type", "video/mp4").setBody(Buffer().write(bytes)))
            val root = temporary.newFolder()
            val target = root.resolve("ready.mp4")
            val progress = mutableListOf<Float>()
            Mp4VideoDownloader().download(TemporaryVideoSource("fixture", server.url("/video").toString(), 90), target) {
                if (it != null) progress += it
                if (it != null && it < 1f) assertThat(target.exists()).isFalse()
            }
            assertThat(target.readBytes()).isEqualTo(bytes)
            assertThat(progress.last()).isEqualTo(1f)
            assertThat(progress.zipWithNext().all { (a,b) -> b >= a }).isTrue()
            assertThat(root.listFiles()!!.map { it.name }).containsExactly("ready.mp4")
        }
    }

    @Test fun invalidOversizedAndFailedResponsesNeverLeavePlayableOrPartialArtifacts(): Unit = runBlocking {
        MockWebServer().use { server ->
            for (response in listOf(MockResponse().setResponseCode(403), MockResponse().setBody("not an mp4 video file"),
                MockResponse().setBody(Buffer().write(fixture())))) {
                server.enqueue(response)
                val root = temporary.newFolder(); val target = root.resolve("ready.mp4")
                val result = runCatching { Mp4VideoDownloader(maximumBytes = 100).download(
                    TemporaryVideoSource("fixture", server.url("/video").toString(), 90), target) {} }
                assertThat(result.isFailure).isTrue()
                assertThat(root.listFiles()!!.toList()).isEmpty()
            }
        }
    }

    @Test fun videoLargerThanOldEightyMiBLimitFitsTheSharedCacheBudget(): Unit = runBlocking {
        val size = 81L * 1024 * 1024
        // Stream generated bytes rather than allocate an entire song video in memory.
        val body = object : okhttp3.ResponseBody() {
            override fun contentType() = null
            override fun contentLength() = size
            override fun source(): okio.BufferedSource = object : okio.Source {
                var remaining = size
                override fun timeout() = okio.Timeout.NONE
                override fun close() = Unit
                override fun read(sink: Buffer, byteCount: Long): Long {
                    if (remaining == 0L) return -1
                    if (remaining == size) {
                        sink.write(byteArrayOf(0, 0, 0, 12, 102, 116, 121, 112, 105, 115, 111, 109))
                        remaining -= 12
                        return 12
                    }
                    val count = minOf(byteCount, remaining, 8192L).toInt()
                    sink.write(ByteArray(count))
                    remaining -= count
                    return count.toLong()
                }
            }.buffer()
        }
        val client = OkHttpClient.Builder().addInterceptor { chain ->
            okhttp3.Response.Builder().request(chain.request()).protocol(okhttp3.Protocol.HTTP_1_1)
                .code(200).message("OK").body(body).build()
        }.build()
        val target = temporary.newFolder().resolve("long-song.mp4")
        Mp4VideoDownloader(client = client).download(
            TemporaryVideoSource("long-song", "https://video.test/song", 360), target) {}
        assertThat(target.length()).isEqualTo(size)
    }

    @Test fun videoUsesValidatedParallelRangesAndOnlyPublishesTheAssembledMp4(): Unit = runBlocking {
        MockWebServer().use { server ->
            val bytes = fixture()
            server.dispatcher = object : okhttp3.mockwebserver.Dispatcher() {
                override fun dispatch(request: okhttp3.mockwebserver.RecordedRequest): MockResponse {
                    val range = request.getHeader("Range")!!.removePrefix("bytes=").split("-")
                    val start = range[0].toInt()
                    val end = minOf(range[1].toInt(), bytes.lastIndex)
                    return MockResponse().setResponseCode(206).setHeader("Content-Type", "video/mp4")
                        .setHeader("Content-Range", "bytes $start-$end/${bytes.size}")
                        .setBody(Buffer().write(bytes, start, end - start + 1))
                }
            }
            val client = OkHttpClient()
            val downloader = Mp4VideoDownloader(client = client, rangeDownloader = ParallelRangeDownloader(client,
                chunkSizeBytes = 4096, minimumParallelSizeBytes = 4096, isEligibleHost = { true }))
            val root = temporary.newFolder()
            val target = root.resolve("video.mp4")
            downloader.download(TemporaryVideoSource("song", server.url("/video").toString(), 1080), target) { progress ->
                if (progress != null && progress < 1f) assertThat(target.exists()).isFalse()
            }
            assertThat(target.readBytes()).isEqualTo(bytes)
            assertThat(server.requestCount).isGreaterThan(1)
            assertThat(root.listFiles()!!.map { it.name }).containsExactly("video.mp4")
        }
    }

    @Test fun cancellingAnInflightHttpRequestRemovesPartialFiles(): Unit = runBlocking {
        MockWebServer().use { server ->
            server.enqueue(MockResponse().setSocketPolicy(SocketPolicy.NO_RESPONSE))
            val root = temporary.newFolder()
            val job = async { Mp4VideoDownloader().download(
                TemporaryVideoSource("fixture", server.url("/video").toString(), 90), root.resolve("ready.mp4")) {} }
            // Yield until the request exists; cancellation must close the real OkHttp call.
            while (server.requestCount == 0) kotlinx.coroutines.delay(5)
            job.cancelAndJoin()
            assertThat(root.listFiles()!!.toList()).isEmpty()
        }
    }
}
